#! /usr/bin/python3

"""Creates a serialized, incremental CMake target for one generated test."""

from __future__ import annotations

import hashlib
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

try:
    from .case_manifest import atomic_write_text
except ImportError:
    from case_manifest import atomic_write_text


def _cmake_quote(path: str | Path) -> str:
    value = str(Path(path).resolve(strict=False)).replace("\\", "/")
    return f'"{value.replace(chr(34), chr(92) + chr(34))}"'


def _safe_target(case_id: str, test_path: Path) -> str:
    safe = re.sub(r"[^A-Za-z0-9_]", "_", case_id).strip("_") or "case"
    digest = hashlib.sha256(str(test_path).encode("utf-8")).hexdigest()[:10]
    return f"c2rust_testgen_{safe[:40]}_{digest}"


def dependency_closure(source_path: str, dependency_map: dict[str, list[str]]) -> list[str]:
    result: set[str] = set()
    pending = [source_path]
    while pending:
        current = pending.pop()
        for dependency in dependency_map.get(current, []):
            if dependency == source_path or dependency in result:
                continue
            result.add(dependency)
            pending.append(dependency)
    return sorted(result)


@dataclass(frozen=True)
class CCaseHarness:
    case_id: str
    target: str
    cmake_path: Path
    configure_command: tuple[str, ...]
    compile_command: tuple[str, ...]
    run_command: tuple[str, ...]
    sources: tuple[Path, ...]


class CMakeCaseHarnessBuilder:
    """Writes the `llm_coverage` CMake file without clearing the build tree."""

    def __init__(self, project: str | Path, build: str | Path):
        self.project = Path(project).resolve()
        self.build = Path(build).resolve()
        self.harness_dir = self.project / "llm_coverage"
        self.output_dir = self.build / "c2rust-testgen-bin"

    def _dependencies(self, source_path: str | None) -> list[str]:
        if not source_path:
            return []
        deps_path = self.project / "project_info/deps_dict.json"
        if not deps_path.is_file():
            return []
        try:
            dependency_map = json.loads(deps_path.read_text(encoding="utf-8"))
        except (OSError, ValueError, TypeError):
            return []
        if not isinstance(dependency_map, dict):
            return []
        return dependency_closure(source_path, dependency_map)

    def prepare(
        self,
        case_id: str,
        test_path: str | Path,
        *,
        source_path: str | None = None,
        compile_source: bool = True,
        dependencies: Iterable[str] | None = None,
    ) -> CCaseHarness:
        test_path = Path(test_path).resolve()
        if not test_path.is_file():
            raise FileNotFoundError(f"Generated C test not found: {test_path}")
        target = _safe_target(case_id, test_path)
        sources: list[Path] = [test_path]
        if compile_source and source_path and not source_path.lower().endswith(
            (".h", ".hpp", ".hxx", ".hh", ".inl", ".tcc")
        ):
            sources.append(Path(source_path).resolve())
        dependency_list = (
            list(dependencies)
            if dependencies is not None
            else self._dependencies(source_path)
        )
        for dependency in dependency_list:
            path = Path(dependency).resolve()
            if path not in sources and path.is_file():
                sources.append(path)

        quoted_sources = "\n  ".join(_cmake_quote(path) for path in sources)
        cmake = (
            "# generated by c2rust-testgen; this target is intentionally singular\n"
            f"add_executable({target} EXCLUDE_FROM_ALL\n  {quoted_sources}\n)\n"
            f"target_link_libraries({target} PRIVATE gmock_main)\n"
            f"target_compile_definitions({target} PRIVATE main=c2rust_testgen_original_main)\n"
            f"set_target_properties({target} PROPERTIES\n"
            f"  RUNTIME_OUTPUT_DIRECTORY {_cmake_quote(self.output_dir)}\n"
            ")\n"
        )
        cmake_path = self.harness_dir / "CMakeLists.txt"
        atomic_write_text(cmake_path, cmake)
        executable = self.output_dir / target
        if os.name == "nt":
            executable = executable.with_suffix(".exe")
        configure_command = (
            "cmake",
            "-S",
            str(self.project),
            "-B",
            str(self.build),
            "-DCMAKE_BUILD_TYPE=Debug",
            "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON",
        )
        compile_command = (
            "cmake",
            "--build",
            str(self.build),
            "--target",
            target,
        )
        return CCaseHarness(
            case_id=case_id,
            target=target,
            cmake_path=cmake_path,
            configure_command=configure_command,
            compile_command=compile_command,
            run_command=(str(executable),),
            sources=tuple(sources),
        )
